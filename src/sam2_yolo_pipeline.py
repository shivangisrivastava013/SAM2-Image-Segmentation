# Task 1 retrieval system

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

commentary_df["retrieval_text"] = (
    commentary_df["game_clock"].astype(str) + " " +
    commentary_df["players_mentioned"].astype(str) + " " +
    commentary_df["event_type"].astype(str) + " " +
    commentary_df["commentary_text"].astype(str)
)

vectorizer = TfidfVectorizer(stop_words="english")
tfidf_matrix = vectorizer.fit_transform(commentary_df["retrieval_text"])

def retrieve_commentary(query, top_k=5):
    query_vec = vectorizer.transform([query])
    similarities = cosine_similarity(query_vec, tfidf_matrix).flatten()
    top_indices = similarities.argsort()[::-1][:top_k]

    results = commentary_df.iloc[top_indices].copy()
    results["similarity"] = similarities[top_indices]

    return results[
        [
            "clip_name",
            "game_clock",
            "start_time",
            "end_time",
            "players_mentioned",
            "event_type",
            "commentary_text",
            "similarity"
        ]
    ]

retrieve_commentary("Which clip shows defensive pressure?", top_k=5)


for _, row in play_segments_df.iterrows():
    video_path = Path(SOURCE_VIDEO_DIRECTORY) / row["clip_name"]

    cap = cv2.VideoCapture(str(video_path))
    fps = cap.get(cv2.CAP_PROP_FPS)
    frame_count = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    # Pick middle frame
    target_frame_id = frame_count // 2
    cap.set(cv2.CAP_PROP_POS_FRAMES, target_frame_id)
    success, frame = cap.read()
    cap.release()

    if not success:
        print("Could not read frame for:", row["clip_name"])
        continue

    # Run YOLO
    results = YOLO_MODEL(frame, conf=0.15, imgsz=1280, verbose=False)
    result = results[0]

    names = result.names
    boxes = result.boxes

    clean_rows = []

    for box in boxes:
        class_id = int(box.cls[0])
        class_name = names[class_id]
        confidence = float(box.conf[0])
        x1, y1, x2, y2 = box.xyxy[0].tolist()

        if class_name in VALID_BASKETBALL_CLASSES:
            clean_rows.append({
                "class_id": class_id,
                "class_name": class_name,
                "confidence": round(confidence, 3),
                "x1": round(x1, 1),
                "y1": round(y1, 1),
                "x2": round(x2, 1),
                "y2": round(y2, 1)
            })

    clean_df = pd.DataFrame(clean_rows)

    # Manually annotate only basketball-relevant detections
    annotated = frame.copy()

    for det in clean_rows:
        x1, y1, x2, y2 = int(det["x1"]), int(det["y1"]), int(det["x2"]), int(det["y2"])
